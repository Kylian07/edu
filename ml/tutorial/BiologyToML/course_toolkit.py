def simulate_multiome(rng: np.random.Generator, n_cells: int = 2500, n_genes: int = 800,
                      n_peaks: int = 2000) -> dict:
    """Simulate a trimodal single-cell experiment: RNA + surface protein (CITE-seq) + chromatin (ATAC).

    Some biology is visible in only one modality, which is why multimodal assays exist:
    naive vs memory T cells and regulatory T cells differ mainly in *protein* (CD45RA/CD45RO,
    CD25); a "primed" monocyte state has open chromatin at interferon genes that are not yet
    transcribed, so it is visible only in *ATAC*.  RNA comes from ``simulate_scrna`` (one
    batch, control donors).  Protein counts include ambient background (see the isotype
    control); ATAC is a binary cell × peak matrix with sparse, depth-dependent capture.

    Returns a dict with ``rna``, ``adt`` and ``atac`` matrices, ``obs`` (true cell type plus
    the hidden states), ``var`` (genes), ``proteins`` and ``peaks`` (each peak's linked gene).
    """
    sc = simulate_scrna(rng, n_cells=n_cells, n_genes=n_genes, n_donors=2, n_batches=1, stim_effect=0.0)
    obs, profiles, genes = sc["obs"].copy(), sc["log_profiles"], np.array(sc["var"].index)
    names = list(profiles.index)
    ttype = obs["true_type"].to_numpy()
    is_t = np.isin(ttype, ["CD4 T", "CD8 T"])
    memory = is_t & (rng.random(n_cells) < 0.5)
    treg = (ttype == "CD4 T") & (rng.random(n_cells) < 0.12)
    primed = (ttype == "Monocyte") & (rng.random(n_cells) < 0.35)
    obs["t_state"] = np.where(is_t, np.where(memory, "memory", "naive"), "")
    obs["is_treg"], obs["is_primed"] = treg, primed
    # surface proteins
    level = np.zeros((n_cells, len(ADT_PANEL)))
    for j, (prot, (_, by_type)) in enumerate(ADT_PANEL.items()):
        for t, v in by_type.items():
            level[ttype == t, j] = v
    pidx = list(ADT_PANEL)
    level[is_t & ~memory, pidx.index("CD45RA")] = 1.0
    level[memory, pidx.index("CD45RO")] = 1.0
    level[treg, pidx.index("CD25")] = 1.0
    size = np.exp(rng.normal(0, 0.3, n_cells))[:, None]
    adt = sample_negative_binomial(rng, size * (15 + 400 * level * rng.uniform(0.6, 1.4, len(pidx))), 6.0)
    # chromatin accessibility: peaks near genes open where the gene is (or is about to be) active
    active = (profiles.to_numpy() > profiles.to_numpy().mean(axis=0) + 0.8).astype(float)
    linked = rng.integers(0, len(genes), n_peaks)
    kind = rng.choice(["promoter", "enhancer", "background"], n_peaks, p=[0.35, 0.35, 0.30])
    linked_gene = np.where(kind == "background", "", genes[linked])
    # every interferon gene gets ten enhancer peaks (the primed-state signal)
    extra = np.repeat([np.flatnonzero(genes == g)[0] for g in INTERFERON_GENES], 10)
    slots = rng.choice(np.flatnonzero(kind == "background"), len(extra), replace=False)
    kind[slots], linked[slots], linked_gene[slots] = "enhancer", extra, genes[extra]
    ifn_peak = np.isin(linked_gene, INTERFERON_GENES)
    t_idx = np.array([names.index(t) for t in ttype])
    logit = rng.normal(-2.5, 0.8, n_peaks) + np.where(kind == "background", 0.0, 3.0 * active[t_idx][:, linked])
    logit[:, ifn_peak] += 3.5 * primed[:, None]
    capture = rng.beta(4, 6, n_cells)[:, None]
    atac = (rng.random((n_cells, n_peaks)) < capture / (1 + np.exp(-logit))).astype(np.int8)
    proteins = pd.DataFrame({"gene": [v[0] for v in ADT_PANEL.values()]}, index=pidx)
    peaks = pd.DataFrame({"kind": kind, "linked_gene": linked_gene, "is_interferon": ifn_peak},
                         index=[f"peak{p:05d}" for p in range(n_peaks)])
    return dict(rna=sc["counts"], adt=adt, atac=atac, obs=obs, var=sc["var"], proteins=proteins, peaks=peaks)


def simulate_perturb_seq(rng: np.random.Generator, n_genes: int = 40, n_targets: int = 15, n_pairs: int = 12,
                         cells_per_perturbation: int = 80, n_control: int = 800, edge_prob: float = 0.08,
                         knockdown: float = 2.0, escape_rate: float = 0.1, noise: float = 0.3,
                         depth: float = 3000) -> dict:
    """Simulate a CRISPR-interference Perturb-seq screen on a known gene-regulatory network.

    The network is a random DAG: each gene is regulated by earlier genes (probability
    ``edge_prob`` per pair) with signed weights.  A cell's deviation from baseline is
    d_g = c·tanh((Σ_parents w·d_parent + ε_g)/c), i.e. linear for small changes but
    *saturating* for large ones, so double knockdowns are not simply the sum of two single
    ones.  A knockdown clamps the target at −``knockdown`` (an intervention, do(X = x)); a
    fraction ``escape_rate`` of cells keep a working gene (guide escape).  Perturbations: one
    control group, ``n_targets`` single knockdowns and ``n_pairs`` double knockdowns.

    Returns a dict with ``expression`` (log scale, cells × genes), ``counts`` (UMIs), ``obs``
    (perturbation label, e.g. "ctrl", "G07", "G07+G12"), ``var``, the true weighted
    adjacency ``W`` (W.loc[parent, child]) and ``true_effect`` (noise-free mean shift per
    perturbation).
    """
    genes = np.array([f"G{j:02d}" for j in range(1, n_genes + 1)], dtype=object)
    order = rng.permutation(n_genes)                                     # hidden topological order
    W = np.zeros((n_genes, n_genes))
    for a in range(n_genes):
        for b in range(a + 1, n_genes):
            if rng.random() < edge_prob:
                W[order[a], order[b]] = rng.choice([-1, 1]) * rng.uniform(0.6, 1.2)
    has_children = np.flatnonzero((W != 0).sum(axis=1) > 0)
    pool = has_children if len(has_children) >= n_targets else np.arange(n_genes)
    targets = rng.choice(pool, n_targets, replace=False)
    pairs = set()
    while len(pairs) < n_pairs:
        a, b = sorted(rng.choice(targets, 2, replace=False))
        pairs.add((a, b))
    conditions = [()] + [(t,) for t in targets] + sorted(pairs)
    sizes = [n_control] + [cells_per_perturbation] * (len(conditions) - 1)
    base = rng.normal(1.0, 1.0, n_genes)                                 # baseline log expression
    sat = 1.5                                                            # saturation scale c

    def propagate(clamp, eps):
        d = np.zeros_like(eps)
        for g in order:
            if g in clamp:
                d[:, g] = np.where(clamp[g], -knockdown, sat * np.tanh((d @ W[:, g] + eps[:, g]) / sat))
            else:
                d[:, g] = sat * np.tanh((d @ W[:, g] + eps[:, g]) / sat)
        return d

    expr, labels, effects = [], [], {}
    for cond, n in zip(conditions, sizes):
        label = "ctrl" if not cond else "+".join(genes[list(cond)])
        clamp = {g: rng.random(n) >= escape_rate for g in cond}
        d = propagate(clamp, rng.normal(0, noise, (n, n_genes)))
        expr.append(base + d)
        labels += [label] * n
        effects[label] = propagate({g: np.ones(1, bool) for g in cond}, np.zeros((1, n_genes)))[0]
    expression = np.vstack(expr)
    prob = np.exp(expression) / np.exp(expression).sum(axis=1, keepdims=True)
    counts = rng.poisson(depth * np.exp(rng.normal(0, 0.2, len(labels)))[:, None] * prob).astype(np.int32)
    obs = pd.DataFrame({"perturbation": labels,
                        "n_targets": [0 if lab == "ctrl" else lab.count("+") + 1 for lab in labels]},
                       index=[f"cell{i:05d}" for i in range(len(labels))])
    var = pd.DataFrame({"baseline": base, "is_target": np.isin(np.arange(n_genes), targets),
                        "topological_rank": np.argsort(order)}, index=genes)
    return dict(expression=expression, counts=counts, obs=obs, var=var,
                W=pd.DataFrame(W, index=genes, columns=genes),
                true_effect=pd.DataFrame(effects, index=genes).T)


# ── Simulators for genomes, proteins and molecules (Modules 24–25, 28–29, 35–40) ───
IUPAC = {"A": "A", "C": "C", "G": "G", "T": "T", "R": "AG", "Y": "CT", "S": "CG", "W": "AT", "K": "GT",
         "M": "AC", "N": "ACGT"}
# Transcription-factor motifs (IUPAC consensus) and their effect on enhancer activity in the
# simulated reporter assay.  The consensus sequences are those of the real factors.
REGULATORY_MOTIFS = {
    "AP-1": ("TGASTCA", 1.0),
    "GATA": ("WGATAR", 0.7),
    "SP1": ("GGGGCGGGG", 0.5),
    "E-box": ("CACGTG", 0.8),
    "REST": ("TTCAGCACC", -1.5),        # repressor
}


def reverse_complement(seq: str) -> str:
    """Reverse complement of a DNA string (IUPAC codes are complemented too)."""
    comp = {"A": "T", "C": "G", "G": "C", "T": "A", "R": "Y", "Y": "R", "S": "S", "W": "W", "K": "M",
            "M": "K", "N": "N"}
    return "".join(comp[b] for b in reversed(seq.upper()))


def find_motif_sites(seq: str, consensus: str) -> list:
    """Start positions where ``consensus`` (IUPAC) matches ``seq`` on either strand (overlaps allowed)."""
    import re
    sites = set()
    for c in {consensus, reverse_complement(consensus)}:
        pattern = "(?=" + "".join(f"[{IUPAC[b]}]" for b in c) + ")"
        sites.update(m.start() for m in re.finditer(pattern, seq))
    return sorted(sites)


def regulatory_activity(seq: str) -> float:
    """Noise-free enhancer activity of a DNA sequence under the course's motif grammar.

    Activity = Σ motif effects (sites in the central half count fully, flanking sites 60 %)
    + 1.0 if an AP-1 and a GATA site lie within 30 bp of each other (cooperative binding)
    + 2·(GC fraction − 0.5).  This is the "true biology" that Module 36's networks must learn.
    """
    L = len(seq)
    total, starts = 0.0, {}
    for name, (consensus, effect) in REGULATORY_MOTIFS.items():
        starts[name] = find_motif_sites(seq, consensus)
        for s in starts[name]:
            total += effect * (1.0 if L / 4 <= s + len(consensus) / 2 <= 3 * L / 4 else 0.6)
    if any(abs(a - g) <= 30 for a in starts["AP-1"] for g in starts["GATA"]):
        total += 1.0
    gc = (seq.count("G") + seq.count("C")) / max(L, 1)
    return total + 2.0 * (gc - 0.5)


def simulate_regulatory_sequences(rng: np.random.Generator, n_seqs: int = 4000, length: int = 200,
                                  motif_rate: float = 1.5, noise: float = 0.3, n_chromosomes: int = 8) -> dict:
    """Simulate an enhancer reporter assay (MPRA / STARR-seq style): DNA sequence → activity.

    Background DNA has a per-sequence GC content; each sequence receives Poisson(``motif_rate``)
    planted motif instances at random positions and orientations (sampled from the IUPAC
    consensus).  The measured activity is ``regulatory_activity(seq)`` plus Gaussian noise,
    so motifs that occur by chance count too, exactly as in real DNA.  Each sequence is
    assigned to a chromosome so that models can be tested on held-out chromosomes.

    Returns a dict with ``sequences`` (list of str), ``activity``, ``label`` (1 = active, top
    40 %), ``chromosome`` and ``sites`` (DataFrame of planted motifs).
    """
    names = list(REGULATORY_MOTIFS)
    seqs, rows = [], []
    for i in range(n_seqs):
        gc = rng.beta(8, 8)
        s = list(rng.choice(list("ACGT"), length, p=[(1 - gc) / 2, gc / 2, gc / 2, (1 - gc) / 2]))
        for _ in range(rng.poisson(motif_rate)):
            m = names[rng.integers(len(names))]
            inst = "".join(rng.choice(list(IUPAC[b])) for b in REGULATORY_MOTIFS[m][0])
            strand = "+" if rng.random() < 0.5 else "-"
            if strand == "-":
                inst = reverse_complement(inst)
            start = int(rng.integers(0, length - len(inst)))
            s[start:start + len(inst)] = list(inst)
            rows.append((i, m, start, strand))
        seqs.append("".join(s))
    activity = np.array([regulatory_activity(s) for s in seqs]) + rng.normal(0, noise, n_seqs)
    label = (activity > np.quantile(activity, 0.6)).astype(int)
    chromosome = np.array([f"chr{c + 1}" for c in rng.integers(0, n_chromosomes, n_seqs)], dtype=object)
    sites = pd.DataFrame(rows, columns=["seq_id", "motif", "start", "strand"])
    return dict(sequences=seqs, activity=activity, label=label, chromosome=chromosome, sites=sites)


