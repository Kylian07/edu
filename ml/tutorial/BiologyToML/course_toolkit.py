def sample_negative_binomial(rng: np.random.Generator, mu, theta):
    """Negative-binomial counts with mean ``mu`` and inverse dispersion ``theta``.

    Variance = mu + mu²/theta (large theta → Poisson).  Drawn as a Gamma–Poisson mixture:
    each count is Poisson with a rate that itself varies from cell to cell.
    """
    mu = np.asarray(mu, float)
    theta = np.broadcast_to(np.asarray(theta, float), mu.shape)
    return rng.poisson(rng.gamma(theta, np.where(mu > 0, mu, 0.0) / theta)).astype(np.int32)


def make_expression_programs(rng: np.random.Generator, n_genes: int, cell_types: dict,
                             n_extra_markers: int = 20, extra_names=()):
    """Log-scale expression profiles (one row per cell type) for a simulated tissue.

    ``cell_types`` maps a type name to (lineage, named marker genes, marker strength).  Every
    type gets its named markers plus ``n_extra_markers`` anonymous ones; types of the same
    lineage share 20 lineage genes.  ``extra_names`` are reserved gene names (placed after the
    markers) that the caller gives its own behaviour.  Returns ``(log_profiles, genes, marker_of)``.
    """
    named = []
    for _, markers, _ in cell_types.values():
        named += [g for g in markers if g not in named]
    reserved = named + [g for g in extra_names if g not in named]
    if len(reserved) > n_genes:
        raise ValueError("n_genes is too small for the requested marker genes")
    genes = np.array(reserved + [f"Gene{j:04d}" for j in range(1, n_genes - len(reserved) + 1)], dtype=object)
    free = np.arange(len(reserved), n_genes)                       # anonymous genes available
    base = rng.normal(0.0, 2.0, n_genes)                           # gene-specific baseline (log scale)
    base[:len(named)] -= 2.0                                       # named markers are low elsewhere
    profiles = np.tile(base, (len(cell_types), 1)) + rng.normal(0, 0.15, (len(cell_types), n_genes))
    marker_of = np.array([""] * n_genes, dtype=object)
    lineages = sorted({v[0] for v in cell_types.values()})
    lineage_genes = {lin: rng.choice(free, 20, replace=False) for lin in lineages}
    for t, (name, (lineage, markers, strength)) in enumerate(cell_types.items()):
        profiles[t, lineage_genes[lineage]] += rng.normal(1.2, 0.3, 20)
        idx = [int(np.flatnonzero(genes == g)[0]) for g in markers]
        profiles[t, idx] += strength + 2.0 + rng.normal(0, 0.2, len(idx))
        extra = rng.choice(free, n_extra_markers, replace=False)
        profiles[t, extra] += rng.normal(0.6 + strength / 2, 0.3, n_extra_markers)
        for j in list(idx) + list(extra):
            marker_of[j] = name if marker_of[j] == "" else marker_of[j] + "/" + name
    return profiles, genes, marker_of


def simulate_scrna(rng: np.random.Generator, n_cells: int = 3000, n_genes: int = 1000, cell_types=None,
                   proportions=None, n_donors: int = 6, n_batches: int = 2, confounded: bool = False,
                   depth: float = 1500, batch_effect: float = 0.25, donor_effect: float = 0.15,
                   stim_effect: float = 1.0, theta: float = 8.0, doublet_rate: float = 0.0,
                   damaged_rate: float = 0.0, cycling_rate: float = 0.0, drop_type_in_batch=None) -> dict:
    """Simulate single-cell RNA-seq UMI counts for a PBMC-like sample collection.

    Design: ``n_donors`` donors, the first half *control* and the second half *stimulated*
    (an interferon response in every cell type plus a monocyte-specific response).  Donor
    ``d`` is sequenced in batch ``d % n_batches`` — or, with ``confounded=True``, every control
    donor in batch 1 and every stimulated donor in batch 2 (a design flaw to learn from).
    Counts are negative binomial around ``depth`` UMIs per cell.  Optional artefacts for
    quality control: doublets, damaged cells (high mitochondrial fraction), cycling cells.
    ``drop_type_in_batch=("B", 1)`` removes B cells from batch 1 (index 1, i.e. "batch2").

    Expression probabilities are renormalised within each cell (a fixed-size library, as in
    sequencing), so in stimulated cells the genes with ``true_logfc == 0`` lose a few per cent of
    their share (about −0.04 on the natural-log scale) to the induced genes: a compositional
    effect that is also present in real data.

    Returns a dict with ``counts`` (cells × genes, int32), ``obs`` (per-cell table with the
    true cell type, donor, batch, condition, …), ``var`` (per-gene table), ``true_logfc``
    (cell type × gene stimulation effect, natural log) and ``log_profiles``.
    """
    cell_types = PBMC_TYPES if cell_types is None else cell_types
    names = list(cell_types)
    T = len(names)
    p = np.full(T, 1 / T) if proportions is None else np.asarray(proportions, float) / np.sum(proportions)
    extra = MITO_GENES + INTERFERON_GENES + CYCLING_GENES
    profiles, genes, marker_of = make_expression_programs(rng, n_genes, cell_types, extra_names=extra)
    G = len(genes)
    is_mito, is_ifn, is_cyc = (np.isin(genes, MITO_GENES), np.isin(genes, INTERFERON_GENES),
                               np.isin(genes, CYCLING_GENES))
    profiles[:, is_mito] = rng.normal(3.0, 0.3, is_mito.sum())          # ≈ 4 % of UMIs are mitochondrial
    profiles[:, is_ifn | is_cyc] = rng.normal(-1.0, 0.4, (T, (is_ifn | is_cyc).sum()))
    # stimulation: interferon genes up everywhere + 40 monocyte-specific responders (up or down)
    true_logfc = np.zeros((T, G))
    true_logfc[:, is_ifn] = stim_effect * rng.normal(1.6, 0.3, is_ifn.sum())
    if "Monocyte" in names:
        responders = rng.choice(np.flatnonzero((marker_of == "") & ~is_mito & ~is_ifn & ~is_cyc), 40, replace=False)
        true_logfc[names.index("Monocyte"), responders] = stim_effect * rng.choice([-1, 1], 40) * rng.normal(1.2, 0.3, 40)
    # donors, batches, conditions
    donor = rng.integers(0, n_donors, n_cells)
    stimulated = donor >= n_donors // 2
    batch = stimulated.astype(int) if confounded else donor % n_batches
    batch = np.minimum(batch, n_batches - 1)
    cell_type = rng.choice(T, n_cells, p=p)
    if drop_type_in_batch is not None:
        t_drop, b_drop = names.index(drop_type_in_batch[0]), drop_type_in_batch[1]
        bad = (cell_type == t_drop) & (batch == b_drop)
        cell_type[bad] = rng.choice(np.delete(np.arange(T), t_drop), bad.sum(), p=np.delete(p, t_drop) / (1 - p[t_drop]))
    batch_shift = rng.normal(0, batch_effect, (n_batches, G))
    batch_depth = np.exp(rng.normal(0, 0.3, n_batches))
    donor_shift = rng.normal(0, donor_effect, (n_donors, G))
    log_rate = (profiles[cell_type] + batch_shift[batch] + donor_shift[donor]
                + true_logfc[cell_type] * stimulated[:, None])
    cycling = rng.random(n_cells) < cycling_rate
    log_rate[np.ix_(cycling, np.flatnonzero(is_cyc))] += 3.0
    damaged = rng.random(n_cells) < damaged_rate
    log_rate[np.ix_(damaged, np.flatnonzero(is_mito))] += 2.2
    lib = depth * batch_depth[batch] * np.exp(rng.normal(0, 0.35, n_cells))
    lib[damaged] *= 0.35
    prob = np.exp(log_rate - log_rate.max(axis=1, keepdims=True))
    prob /= prob.sum(axis=1, keepdims=True)
    theta_g = theta * np.exp(rng.normal(0, 0.5, G))
    mu = lib[:, None] * prob
    doublet = rng.random(n_cells) < doublet_rate
    partner = rng.integers(0, n_cells, n_cells)
    mu[doublet] = 0.9 * mu[doublet] + 0.9 * mu[partner[doublet]]       # two cells in one droplet
    counts = sample_negative_binomial(rng, mu, theta_g)
    obs = pd.DataFrame({
        "cell_type": np.where(doublet, "Doublet", np.array(names, dtype=object)[cell_type]),
        "true_type": np.array(names, dtype=object)[cell_type],
        "lineage": np.array([cell_types[n][0] for n in names], dtype=object)[cell_type],
        "donor": [f"donor{d + 1}" for d in donor],
        "condition": np.where(stimulated, "stimulated", "control"),
        "batch": [f"batch{b + 1}" for b in batch],
        "n_counts": counts.sum(axis=1),
        "n_genes": (counts > 0).sum(axis=1),
        "pct_mito": 100 * counts[:, is_mito].sum(axis=1) / np.maximum(counts.sum(axis=1), 1),
        "is_doublet": doublet, "is_damaged": damaged, "is_cycling": cycling,
    }, index=[f"cell{i:05d}" for i in range(n_cells)])
    var = pd.DataFrame({"marker_of": marker_of, "is_mito": is_mito, "is_interferon": is_ifn,
                        "is_cycling": is_cyc, "theta": theta_g}, index=genes)
    return dict(counts=counts, obs=obs, var=var, log_profiles=pd.DataFrame(profiles, index=names, columns=genes),
                true_logfc=pd.DataFrame(true_logfc, index=names, columns=genes))


def simulate_differentiation(rng: np.random.Generator, n_cells: int = 2000, n_genes: int = 200,
                             branch_time: float = 0.35, n_days: int = 4, depth: float = 25.0,
                             priming: float = 0.0) -> dict:
    """Simulate a differentiation time course: progenitors split into fate A or fate B.

    Every gene follows the transcription kinetics used by RNA-velocity methods,
    du/dt = α(t) − β·u (unspliced pre-mRNA) and ds/dt = β·u − γ·s (spliced mRNA), where the
    transcription rate α(t) switches on and off along each lineage.  Gene programmes:
    progenitor genes (switch off), fate-A genes, fate-B genes, transient genes and
    housekeeping genes.  Cells are collected on ``n_days`` sampling days (snapshots overlap
    in latent time, as in a real time course).  ``priming > 0`` lets a few fate genes
    differ slightly *before* the branch point (early fate bias).

    Returns a dict with ``spliced`` and ``unspliced`` counts (cells × genes), ``obs`` (true
    latent time, sampling day, state and eventual fate), ``var`` (programme and kinetic
    rates of every gene) and the true ``velocity`` ds/dt of every cell.
    """
    grid = np.linspace(0.0, 1.0, 801)
    dt = grid[1] - grid[0]
    program = rng.choice(["progenitor", "fate A", "fate B", "transient", "housekeeping"], n_genes,
                         p=[0.25, 0.25, 0.25, 0.1, 0.15])
    alpha_on = np.exp(rng.normal(np.log(4.0), 0.5, n_genes))
    beta = np.exp(rng.normal(np.log(12.0), 0.3, n_genes))                # splicing rate
    gamma = np.exp(rng.normal(np.log(6.0), 0.4, n_genes))                # degradation rate
    t_on = np.where(program == "fate A", rng.uniform(branch_time, 0.75, n_genes),
                    np.where(program == "fate B", rng.uniform(branch_time, 0.75, n_genes),
                             np.where(program == "transient", rng.uniform(0.1, 0.6, n_genes), 0.0)))
    t_off = np.where(program == "progenitor", rng.uniform(branch_time - 0.1, branch_time + 0.2, n_genes),
                     np.where(program == "transient", t_on + rng.uniform(0.15, 0.3, n_genes), 2.0))
    us = np.zeros((2, len(grid), n_genes, 2))                            # lineage, time, gene, (u, s)
    for lineage, own in enumerate(["fate A", "fate B"]):
        on = (grid[:, None] >= t_on) & (grid[:, None] < t_off)
        silent = np.isin(program, ["fate A", "fate B"]) & (program != own)
        alpha = np.where(on & ~silent, alpha_on, 0.0)
        if priming > 0:                                                  # weak early bias towards own fate
            early = (program == own) & (grid[:, None] < t_on) & (grid[:, None] > 0.1)
            alpha = np.where(early, priming * alpha_on, alpha)
        alpha = np.where(program == "housekeeping", alpha_on, alpha)
        u, s = alpha[0] / beta, alpha[0] / gamma                         # start at steady state
        for k in range(len(grid)):
            us[lineage, k, :, 0], us[lineage, k, :, 1] = u, s
            u_next = alpha[k] / beta + (u - alpha[k] / beta) * np.exp(-beta * dt)   # exact for constant α
            s = s + dt * (beta * u - gamma * s)
            u = u_next
    day = rng.integers(0, n_days, n_cells)
    centre = 0.05 + 0.9 * day / max(n_days - 1, 1)
    time_ = np.clip(rng.normal(centre, 0.09), 0.0, 1.0)
    fate = rng.integers(0, 2, n_cells)                                   # eventual fate of every cell
    k = np.clip(np.round(time_ / dt).astype(int), 0, len(grid) - 1)
    u, s = us[fate, k, :, 0], us[fate, k, :, 1]
    lib = depth * np.exp(rng.normal(0, 0.25, n_cells))[:, None]
    unspliced = rng.poisson(lib * u).astype(np.int32)
    spliced = rng.poisson(lib * s).astype(np.int32)
    state = np.where(time_ < branch_time, "progenitor", np.where(fate == 0, "fate A", "fate B"))
    obs = pd.DataFrame({"time": time_, "day": day, "state": state, "fate": np.where(fate == 0, "A", "B")},
                       index=[f"cell{i:05d}" for i in range(n_cells)])
    genes = np.array([f"Gene{j:03d}" for j in range(1, n_genes + 1)], dtype=object)
    var = pd.DataFrame({"program": program, "alpha_on": alpha_on, "beta": beta, "gamma": gamma,
                        "t_on": t_on, "t_off": np.minimum(t_off, 1.0)}, index=genes)
    return dict(spliced=spliced, unspliced=unspliced, obs=obs, var=var, velocity=beta * u - gamma * s)


# Tumour-microenvironment cell types for the spatial simulator (lineage, marker names, strength).
TISSUE_TYPES = {
    "Tumor": ("epithelial", ["EPCAM", "KRT8", "KRT18", "CEACAM5"], 2.4),
    "Epithelial": ("epithelial", ["KRT5", "KRT14", "TP63", "KRT15"], 2.2),
    "Fibroblast": ("stromal", ["COL1A1", "COL1A2", "DCN", "LUM"], 2.4),
    "Endothelial": ("stromal", ["PECAM1", "VWF", "CLDN5", "CDH5"], 2.2),
    "T cell": ("immune", ["CD3E", "CD8A", "GZMB", "NKG7"], 2.0),
    "Macrophage": ("immune", ["CD68", "CD163", "C1QA", "C1QB"], 2.2),
}
HYPOXIA_GENES = ["VEGFA", "CA9", "SLC2A1", "LDHA", "BNIP3", "PGK1"]
EXHAUSTION_GENES = ["PDCD1", "HAVCR2", "LAG3", "TOX"]


def simulate_spatial_tissue(rng: np.random.Generator, n_cells: int = 4000, n_genes: int = 300,
                            spot_spacing: float = 0.05, depth: float = 400) -> dict:
    """Simulate a spatial-transcriptomics section of a tumour (unit square, single-cell resolution).

    Domains: *tumour core* (a disc), *invasive margin* (a ring around it), *normal epithelium*
    (a band along the top edge) and *stroma* (everything else); each domain has its own
    cell-type composition.  Spatial signals beyond cell type: a hypoxia programme that rises
    towards the tumour centre, and an exhaustion programme in T cells that grows with the
    number of tumour cells nearby (cell–cell communication).  Cells are also aggregated
    into Visium-like spots (hexagonal grid, spacing ``spot_spacing``).

    The programme genes have a fixed baseline in every cell type (hypoxia genes moderate,
    exhaustion genes low), so their spatial patterns come only from the planted programmes.

    Returns a dict with ``cells`` (x, y, domain, cell_type), ``counts`` (cells × genes),
    ``var``, ``spots`` (x, y, number of cells), ``spot_counts``, ``spot_proportions``
    (true cell-type fractions per spot) and ``reference`` (mean expression profile per type).
    """
    names = list(TISSUE_TYPES)
    profiles, genes, marker_of = make_expression_programs(rng, n_genes, TISSUE_TYPES, n_extra_markers=12,
                                                          extra_names=HYPOXIA_GENES + EXHAUSTION_GENES)
    profiles[:, np.isin(genes, HYPOXIA_GENES)] = 0.5                     # moderate baseline everywhere
    profiles[:, np.isin(genes, EXHAUSTION_GENES)] = -1.0                 # low baseline everywhere
    x, y = rng.random(n_cells), rng.random(n_cells)
    centre, radius = np.array([0.62, 0.42]), 0.2
    r = np.hypot(x - centre[0], y - centre[1])
    domain = np.where(r < radius, "tumor core", np.where(r < radius + 0.08, "invasive margin",
                      np.where(y > 0.85 + 0.03 * np.sin(8 * x), "epithelium", "stroma")))
    composition = {  # Tumor, Epithelial, Fibroblast, Endothelial, T cell, Macrophage
        "tumor core": [0.80, 0.00, 0.03, 0.07, 0.03, 0.07],
        "invasive margin": [0.25, 0.00, 0.15, 0.05, 0.30, 0.25],
        "epithelium": [0.00, 0.85, 0.10, 0.02, 0.02, 0.01],
        "stroma": [0.00, 0.02, 0.62, 0.16, 0.08, 0.12],
    }
    cell_type = np.array([rng.choice(len(names), p=composition[d]) for d in domain])
    log_rate = profiles[cell_type].copy()
    hyp = np.isin(genes, HYPOXIA_GENES)
    log_rate[:, hyp] += 3.0 * np.clip(1 - r / radius, 0, 1)[:, None] * (cell_type == 0)[:, None]
    from scipy.spatial import cKDTree
    tree = cKDTree(np.c_[x, y])
    n_tumor_nb = np.array([np.sum(cell_type[nb] == 0) for nb in tree.query_ball_point(np.c_[x, y], 0.04)])
    exh = np.isin(genes, EXHAUSTION_GENES)
    log_rate[:, exh] += (0.5 * np.minimum(n_tumor_nb, 8) * (cell_type == names.index("T cell")))[:, None]
    prob = np.exp(log_rate - log_rate.max(axis=1, keepdims=True))
    prob /= prob.sum(axis=1, keepdims=True)
    lib = depth * np.exp(rng.normal(0, 0.3, n_cells))
    counts = sample_negative_binomial(rng, lib[:, None] * prob, 10.0)
    # Visium-like spots on a hexagonal grid
    sx, sy = np.meshgrid(np.arange(spot_spacing / 2, 1, spot_spacing), np.arange(spot_spacing / 2, 1, spot_spacing * 0.866))
    sx = sx + (np.arange(sx.shape[0]) % 2)[:, None] * spot_spacing / 2
    spot_xy = np.c_[sx.ravel(), sy.ravel()]
    spot_xy = spot_xy[(spot_xy[:, 0] < 1) & (spot_xy[:, 1] < 1)]
    members = tree.query_ball_point(spot_xy, spot_spacing * 0.45)
    spot_counts = np.array([counts[m].sum(axis=0) if m else np.zeros(len(genes), int) for m in members])
    props = np.array([np.bincount(cell_type[m], minlength=len(names)) / max(len(m), 1) for m in members])
    cells = pd.DataFrame({"x": x, "y": y, "domain": domain, "cell_type": np.array(names, dtype=object)[cell_type],
                          "n_tumor_neighbours": n_tumor_nb}, index=[f"cell{i:05d}" for i in range(n_cells)])
    spots = pd.DataFrame({"x": spot_xy[:, 0], "y": spot_xy[:, 1], "n_cells": [len(m) for m in members]},
                         index=[f"spot{i:04d}" for i in range(len(spot_xy))])
    reference = pd.DataFrame(np.exp(profiles) / np.exp(profiles).sum(axis=1, keepdims=True), index=names, columns=genes)
    var = pd.DataFrame({"marker_of": marker_of, "is_hypoxia": hyp, "is_exhaustion": exh}, index=genes)
    return dict(cells=cells, counts=counts, var=var, spots=spots, spot_counts=spot_counts.astype(np.int32),
                spot_proportions=pd.DataFrame(props, index=spots.index, columns=names), reference=reference)


