"""
course_toolkit.py — shared helper functions for the BiologyToML curriculum
==========================================================================

Every notebook in ``notebooks/`` is *self-contained* (it runs alone on Google
Colab), so the helpers a notebook needs are copied verbatim into its
"🧰 Course toolkit" cell.  This file is the single reference copy of those
helpers: if you fix a bug here, copy the fix into the notebooks that use the
function (``python validate_notebooks.py`` reports every copy that differs).

What is in here
---------------
* **No stored data, no downloads.** Every data set of the course is generated by code.
  The classic examples of 02-620 (leukaemia expression, T-cell signalling, prostate
  cancer, breast-tumour features, blood-cell cytometry, microscopy images) are replaced by
  synthetic look-alikes with a fixed default seed, so every notebook sees the same data.
  The small classic worked examples (PlayTennis, the alarm network, the two-dice HMM, …)
  are typed in as tables.  See ``DATA.md``.
* **Simulators** with known ground truth for the frontier modules (24–44): single-cell
  counts, differentiation with spliced/unspliced RNA, spatial tissue, multimodal
  CITE-seq/ATAC, Perturb-seq on a gene network, genotypes with linkage
  disequilibrium, enhancer sequences with a motif grammar, protein families from a
  Potts model, an idealised protein structure and a small-molecule library.
* **Small numerical and plotting helpers.**

Conventions used everywhere in the course
-----------------------------------------
* A data set is a matrix ``X`` with **N rows = samples** (individuals, patients,
  cells) and **J columns = features** (SNPs, genes, proteins).  Other textbooks call
  the number of features *n*, *K* or *p*; the notebooks say so where it matters.
* Genotypes are coded 0/1/2 = number of copies of one chosen allele
  (AA = 0, AT = 1, TT = 2).
* Class labels are ``y ∈ {0, 1}`` (0 = healthy / ALL / negative); the SVM module
  converts them to ``{−1, +1}``.
* ``log`` is the natural logarithm; entropies use ``log2`` and are in bits.
* Randomness always flows through a NumPy ``Generator`` created from ``SEED``.

Requires NumPy, pandas and Matplotlib (SciPy for two simulators).  Educational code:
clarity over speed.
"""
