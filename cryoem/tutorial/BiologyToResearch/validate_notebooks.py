#!/usr/bin/env python3
"""Check the BiologyToResearch course.

    python validate_notebooks.py            # structure, outputs stripped, toolkit copies, Colab badges, relative links,
                                            # and "nothing stored": no data files in the folder, and no code downloads
                                            # anything except the toolkit's PDB download (fetch_pdb, PDB mirrors only)
    python validate_notebooks.py --execute  # ...and execute every notebook (≈ 70–90 min on a laptop CPU)
    python validate_notebooks.py --execute 08 34   # execute only modules 08 and 34

Exit status is non-zero if any check fails.
"""
import ast
import os
import re
import sys
import time
from pathlib import Path

import nbformat
from nbformat.validator import validate

ROOT = Path(__file__).resolve().parent
NB_DIR = ROOT / "notebooks"
COLAB = "https://colab.research.google.com/github/xulabs/edu/blob/main/cryoem/tutorial/BiologyToResearch/notebooks/"
EXPECTED = 35
# "Nothing stored" policy: the repository holds no data. Atomic models are downloaded from the PDB at run time by the
# toolkit's `fetch_pdb` (and cached outside the repository); every image, map and dataset is generated by code. No other
# code may download anything, and the PDB download may only use the PDB's own servers.
NETWORK_FUNCTIONS = {"_pdb_urls", "fetch_pdb"}
PDB_HOSTS = ("https://files.rcsb.org/", "https://files.wwpdb.org/", "https://www.ebi.ac.uk/pdbe/")
DATA_SUFFIXES = {".mrc", ".mrcs", ".map", ".rec", ".st", ".pdb", ".ent", ".cif", ".gz", ".zip", ".tar", ".npy", ".npz",
                 ".h5", ".hdf5", ".pt", ".pth", ".ckpt", ".pkl", ".tif", ".tiff", ".png", ".jpg", ".jpeg", ".gif",
                 ".svg", ".csv", ".star", ".em"}
ALLOWED_DATA_FILES = {"publication_map.csv"}                     # a table of papers, not data
DOWNLOAD_PATTERNS = re.compile(r"urllib|urlopen|requests\.(get|post)|wget |curl |pooch|hf_hub_download|"
                               r"torchvision\.datasets|fetch_openml|load_dataset\(|gdown|zenodo|rcsb\.org|ebi\.ac\.uk/emdb")
problems = []


def fail(msg):
    problems.append(msg)
    print("  ✗", msg)


# ── reference toolkit definitions ──
toolkit_src = (ROOT / "course_toolkit.py").read_text()
toolkit = {}
for node in ast.parse(toolkit_src).body:
    if isinstance(node, ast.FunctionDef):
        toolkit[node.name] = ast.dump(node)
    elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
        toolkit[node.targets[0].id] = ast.dump(node)


def check_links(text, base, where):
    """Every relative markdown link must point to an existing file or folder."""
    for target in re.findall(r"\]\(([^)\s]+)\)", text):
        if re.match(r"^(https?:|mailto:|#|\\)", target):
            continue
        path = (base / target.split("#")[0]).resolve()
        if not path.exists():
            fail(f"{where}: broken relative link → {target}")


# ── notebooks ──
paths = sorted(NB_DIR.glob("*.ipynb"))
print(f"Found {len(paths)} notebooks")
if len(paths) != EXPECTED:
    fail(f"expected {EXPECTED} notebooks, found {len(paths)}")
for i, path in enumerate(paths):
    print(f"• {path.name}")
    nb = nbformat.read(path, as_version=4)
    try:
        validate(nb)
    except Exception as e:  # noqa: BLE001
        fail(f"{path.name}: invalid notebook schema ({e})")
    if not path.name.startswith(f"{i:02d}_"):
        fail(f"{path.name}: expected module number {i:02d}")
    if nb.cells[0].cell_type != "markdown":
        fail(f"{path.name}: first cell must be markdown")
    first = nb.cells[0].source
    if COLAB + path.name not in first:
        fail(f"{path.name}: Colab badge missing or pointing elsewhere")
    for key in ("Hardware target", "Prerequisites", "Estimated time", "Lab papers covered"):
        if key not in first:
            fail(f"{path.name}: key-information table lacks '{key}'")
    md = "\n".join(c.source for c in nb.cells if c.cell_type == "markdown")
    for section in ("Learning objectives", "Checkpoint", "Questions", "References"):
        if section not in md:
            fail(f"{path.name}: missing '{section}' section")
    check_links(md, NB_DIR, path.name)
    code_cells = [c for c in nb.cells if c.cell_type == "code"]
    if any(c.get("outputs") or c.get("execution_count") for c in code_cells):
        fail(f"{path.name}: outputs must be stripped before committing")
    code = "\n".join(c.source for c in code_cells if not c.source.lstrip().startswith(("!", "%")))
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        fail(f"{path.name}: code does not parse ({e})")
        continue
    own_code = []                                                # everything except verified toolkit copies
    for node in tree.body:
        name = node.name if isinstance(node, ast.FunctionDef) else (
            node.targets[0].id if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) else None)
        if name in toolkit and ast.dump(node) != toolkit[name]:
            fail(f"{path.name}: toolkit copy of '{name}' differs from course_toolkit.py")
        if name not in toolkit:
            own_code.append(ast.get_source_segment(code, node) or "")
    hits = sorted({m.group(0) for m in DOWNLOAD_PATTERNS.finditer("\n".join(own_code))})
    if hits:
        fail(f"{path.name}: code appears to download data ({', '.join(hits)}) — only the toolkit's fetch_pdb may")

# ── the toolkit downloads only PDB files, only in fetch_pdb, only from the PDB's servers ──
toolkit_tree = ast.parse(toolkit_src)
for node in toolkit_tree.body:
    segment = ast.get_source_segment(toolkit_src, node) or ""
    if isinstance(node, ast.FunctionDef) and node.name in NETWORK_FUNCTIONS:
        for url in re.findall(r"https?://[^\s\"']+", segment):
            if not url.startswith(PDB_HOSTS):
                fail(f"course_toolkit.py: {node.name} uses a non-PDB address {url}")
        continue
    toolkit_hits = sorted({m.group(0) for m in DOWNLOAD_PATTERNS.finditer(segment)})
    if toolkit_hits and not isinstance(node, ast.Expr):            # the module docstring may mention the PDB
        fail(f"course_toolkit.py: code outside fetch_pdb appears to download data ({', '.join(toolkit_hits)})")

# ── nothing stored: no data files anywhere in the course folder ──
for p in sorted(ROOT.rglob("*")):
    skip = {"__pycache__", ".ipynb_checkpoints", ".git"} & set(p.parts)
    if p.is_file() and not skip and p.suffix.lower() in DATA_SUFFIXES and p.name not in ALLOWED_DATA_FILES:
        fail(f"data file in the course folder: {p.relative_to(ROOT)} — nothing may be stored in the repository")

# ── companion documents ──
for doc in ["README.md", "PAPER_ATLAS.md", "READING_GUIDE.md", "GLOSSARY.md", "INSTRUCTOR_GUIDE.md"]:
    p = ROOT / doc
    if not p.exists():
        fail(f"missing {doc}")
        continue
    check_links(p.read_text(), ROOT, doc)
print(f"\nStructural checks: {'OK' if not problems else f'{len(problems)} problem(s)'}")

# ── optional execution ──
if "--execute" in sys.argv:
    from nbclient import NotebookClient

    only = {a for a in sys.argv[1:] if a.isdigit()}
    os.environ.setdefault("OMP_NUM_THREADS", "2")
    for path in paths:
        if only and path.name[:2] not in only:
            continue
        nb = nbformat.read(path, as_version=4)
        t0 = time.time()
        try:
            NotebookClient(nb, timeout=1200, kernel_name="python3", resources={"metadata": {"path": str(NB_DIR)}}).execute()
            print(f"  ✓ executed {path.name} in {time.time() - t0:.0f} s")
        except Exception as e:  # noqa: BLE001
            fail(f"{path.name}: execution failed — {type(e).__name__}: {str(e)[:300]}")

sys.exit(1 if problems else 0)
