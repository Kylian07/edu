#!/usr/bin/env python3
"""Check the BiologyToMath course.

    python validate_notebooks.py               # structure, outputs stripped, toolkit copies, Colab badges, links
    python validate_notebooks.py --execute     # ...and execute every notebook (≈ 3–5 min on a laptop CPU)
    python validate_notebooks.py --execute 07 12   # execute only modules 07 and 12
    python validate_notebooks.py --only 07 08      # check only modules 07 and 08 (while writing them)

Exit status is non-zero if any check fails.
"""
import ast
import os
import re
import sys
import time
from pathlib import Path

import nbformat
from nbformat.validator import validate

ROOT = Path(__file__).resolve().parent
NB_DIR = ROOT / "notebooks"
COLAB = "https://colab.research.google.com/github/xulabs/edu/blob/main/math/tutorial/BiologyToMath/notebooks/"
EXPECTED = 29                      # 00–01 getting started, 02–27 the 02-680 topics, 28 capstone
CAPSTONE = EXPECTED - 1
KEYS = ("Hardware target", "Core frameworks", "Prerequisites", "Estimated time", "02-680 topics covered")
SECTIONS = ("Learning objectives", "Contents", "The biological question", "Environment setup", "Key takeaways",
            "Checkpoint", "Questions & discussion", "Bonus", "Lab note", "References", "Next")
COLAB_BADGE = "[![Open In Colab](https://colab.research.google.com/assets/colab-badge.svg)]"
# Tutorials are self-contained: they teach the lecture content instead of pointing to slides, and they never
# depend on how 02-680 numbers or orders its lectures and notes (which change from year to year).
COURSE_REFS = [r"(?i)\bslides?\b", r"(?i)\bslide\s*deck", "📑",
               r"(?i)\blectures?\s*#?\s*\d", r"(?i)\btopics?\s*#?\s*\d", r"(?i)\bnotes?\s*#?\s*\d",
               r"(?i)\b(first|second|third|last|previous|next|final|later|earlier|upcoming)\s+lectures?\b",
               r"(?i)\bweek\s+\d+\s+of\s+02-680", r"\b0\d\d[ _][A-Z][a-z]", r"\b\d\d_[A-Z][A-Za-z_]*\.(tex|pdf)"]
# Everything is generated by code: no pictures, no data files, no downloads, no bundled real data.
IMAGE_REFS = [r"!\[", r"<img\b", r"data:image"]
DATA_CODE = [r"urlopen", r"\brequests\.", r"\bwget\b", r"\bcurl\b", r"pd\.read_", r"np\.load(txt)?\(",
             r"\bload_(iris|breast_cancer|digits|diabetes|wine|linnerud)\b", r"\bfetch_[a-z_]+\(", r"\bopen\("]
DATA_SUFFIXES = (".csv", ".tsv", ".gz", ".zip", ".rda", ".rdata", ".rds", ".h5", ".h5ad", ".npz", ".npy", ".pkl",
                 ".parquet", ".xlsx", ".loom", ".mtx", ".png", ".jpg", ".jpeg", ".gif", ".svg", ".pdf")
MAX_FILE_BYTES = 400_000           # keep the repository slim: no data files, no stored outputs
DISCLAIMER = "For research and educational purposes only, not to be used for clinical diagnosis."
MIN_IN_WORDS = 5                   # every topic module reads its equations aloud ("*In words:*")
problems = []


def fail(msg):
    problems.append(msg)
    print("  ✗", msg)


# ── reference toolkit definitions ──
toolkit_src = (ROOT / "course_toolkit.py").read_text()
toolkit = {}
for node in ast.parse(toolkit_src).body:
    if isinstance(node, ast.FunctionDef):
        toolkit[node.name] = ast.dump(node)
    elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
        toolkit[node.targets[0].id] = ast.dump(node)


def check_links(text, base, where):
    """Every relative markdown link must point to an existing file or folder."""
    for target in re.findall(r"\]\(([^)\s]+)\)", text):
        if re.match(r"^(https?:|mailto:|#|\\)", target):
            continue
        path = (base / target.split("#")[0].replace("%20", " ").replace("%26", "&")).resolve()
        if "--only" in sys.argv and re.match(r"^\d\d_[a-z0-9_]+\.ipynb$", target):
            continue                   # sibling modules may not be written yet while working module by module
        if not path.exists():
            fail(f"{where}: broken relative link → {target}")


def check_course_refs(text, where):
    for pat in COURSE_REFS:
        for m in re.finditer(pat, text):
            ctx = text[max(0, m.start() - 40):m.end() + 40].replace("\n", " ")
            fail(f"{where}: refers to lecture slides or to lecture/notes numbering — '…{ctx}…'")
            break


# ── notebooks ──
ONLY = "--only" in sys.argv
selected = {a.zfill(2) for a in sys.argv[1:] if a.isdigit()}
all_paths = sorted(NB_DIR.glob("*.ipynb"))
paths = [p for p in all_paths if not ONLY or p.name[:2] in selected]
print(f"Found {len(all_paths)} notebooks" + (f"; checking {len(paths)}" if ONLY else ""))
if not ONLY:
    if len(all_paths) != EXPECTED:
        fail(f"expected {EXPECTED} notebooks, found {len(all_paths)}")
    for k, p in enumerate(all_paths):
        if not p.name.startswith(f"{k:02d}_"):
            fail(f"{p.name}: expected module number {k:02d}")
next_file = {int(p.name[:2]): p.name for p in all_paths if p.name[:2].isdigit()}
for path in paths:
    i = int(path.name[:2])
    print(f"• {path.name}")
    nb = nbformat.read(path, as_version=4)
    try:
        validate(nb)
    except Exception as e:  # noqa: BLE001
        fail(f"{path.name}: invalid notebook schema ({e})")
    if nb.cells[0].cell_type != "markdown":
        fail(f"{path.name}: first cell must be markdown")
    first = nb.cells[0].source
    if COLAB + path.name not in first:
        fail(f"{path.name}: Colab badge missing or pointing elsewhere")
    for key in KEYS + (("Builds on",) if i == CAPSTONE else ()):
        if f"**{key}**" not in first:
            fail(f"{path.name}: key-information table lacks '{key}'")
    if DISCLAIMER not in first:
        fail(f"{path.name}: the educational-use disclaimer is missing from the first cell")
    md = "\n".join(c.source for c in nb.cells if c.cell_type == "markdown")
    for section in SECTIONS:
        if section not in md:
            fail(f"{path.name}: missing '{section}' section")
    if i < CAPSTONE and "Lecture notes" not in md:
        fail(f"{path.name}: missing '📘 Lecture notes' boxes")
    if 2 <= i < CAPSTONE:
        if "🌉 Bridge" not in md:
            fail(f"{path.name}: missing '🌉 Bridge' boxes (where the topic is used in biology and in later courses)")
        if md.count("In words:") < MIN_IN_WORDS:
            fail(f"{path.name}: only {md.count('In words:')} '*In words:*' readings of equations (need ≥ {MIN_IN_WORDS})")
    if i < CAPSTONE and i + 1 in next_file and next_file[i + 1] not in md:
        fail(f"{path.name}: the ➡️ Next section should link to {next_file[i + 1]}")
    everything = "\n".join(c.source for c in nb.cells)
    check_course_refs(everything, path.name)
    for c in nb.cells:
        if c.get("attachments"):
            fail(f"{path.name}: cell attachments (stored pictures) are not allowed")
    for pat in IMAGE_REFS:
        if re.search(pat, md.replace(COLAB_BADGE, "")):
            fail(f"{path.name}: embedded or linked picture found ({pat}); draw figures with code instead")
    check_links(md, NB_DIR, path.name)
    code_cells = [c for c in nb.cells if c.cell_type == "code"]
    if any(c.get("outputs") or c.get("execution_count") for c in code_cells):
        fail(f"{path.name}: outputs must be stripped before committing")
    code = "\n".join(c.source for c in code_cells if not c.source.lstrip().startswith(("!", "%")))
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        fail(f"{path.name}: code does not parse ({e})")
        continue
    if "SEED" not in code:
        fail(f"{path.name}: no global SEED defined")
    for pat in DATA_CODE:
        if re.search(pat, code):
            fail(f"{path.name}: code reads or downloads data ({pat}); generate data with code instead")
    for node in tree.body:
        name = node.name if isinstance(node, ast.FunctionDef) else (
            node.targets[0].id if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) else None)
        if name in toolkit and ast.dump(node) != toolkit[name]:
            fail(f"{path.name}: toolkit copy of '{name}' differs from course_toolkit.py")

# ── repository stays slim: data and pictures are simulated or drawn, never stored ──
for p in ([] if ONLY else ROOT.rglob("*")):
    rel = p.relative_to(ROOT)
    if p.is_dir() or "__pycache__" in rel.parts or ".ipynb_checkpoints" in rel.parts:
        continue
    if p.suffix.lower() in DATA_SUFFIXES:
        fail(f"{rel}: data files and pictures must not be stored in the repository (generate them with code)")
    if p.stat().st_size > MAX_FILE_BYTES:
        fail(f"{rel}: {p.stat().st_size / 1e3:.0f} kB is larger than {MAX_FILE_BYTES / 1e3:.0f} kB")

# ── companion documents ──
for doc in ([] if ONLY else ["README.md", "STUDY_GUIDE.md", "GLOSSARY.md", "INSTRUCTOR_GUIDE.md", "DATA.md"]):
    p = ROOT / doc
    if not p.exists():
        fail(f"missing {doc}")
        continue
    text = p.read_text()
    check_links(text, p.parent, doc)
    check_course_refs(text, doc)
print(f"\nStructural checks: {'OK' if not problems else f'{len(problems)} problem(s)'}")

# ── optional execution ──
if "--execute" in sys.argv:
    from nbclient import NotebookClient

    only = {a.zfill(2) for a in sys.argv[1:] if a.isdigit()}
    os.environ.setdefault("OMP_NUM_THREADS", "2")
    os.environ.setdefault("MPLBACKEND", "Agg")
    for path in paths:
        if only and path.name[:2] not in only:
            continue
        nb = nbformat.read(path, as_version=4)
        t0 = time.time()
        try:
            NotebookClient(nb, timeout=1200, kernel_name="python3", resources={"metadata": {"path": str(NB_DIR)}}).execute()
            print(f"  ✓ executed {path.name} in {time.time() - t0:.0f} s")
        except Exception as e:  # noqa: BLE001
            fail(f"{path.name}: execution failed — {type(e).__name__}: {str(e)[:300]}")

sys.exit(1 if problems else 0)
