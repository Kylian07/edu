# ── Logic ───────────────────────────────────────────────────────────────────
def implies(p: bool, q: bool) -> bool:
    """Material implication p ⇒ q: false only when p is true and q is false."""
    return (not p) or q


def iff(p: bool, q: bool) -> bool:
    """Biconditional p ⇔ q: true when p and q have the same truth value."""
    return p == q


def xor(p: bool, q: bool) -> bool:
    """Exclusive or p ⊕ q: true when exactly one of p, q is true."""
    return p != q


def truth_table(formulas: dict, variables: list, letters: bool = True) -> pd.DataFrame:
    """Truth table of one or more Boolean formulas.

    ``variables`` is a list of names such as ``["p", "q"]``; ``formulas`` maps a column
    title to a Python function of those variables, e.g. ``{"p ⇒ q": lambda p, q: implies(p, q)}``.
    Rows run through every assignment in the textbook order (T…T first, F…F last).
    With ``letters=True`` the table shows "T"/"F"; otherwise it holds Python booleans.
    """
    rows = []
    for values in itertools.product([True, False], repeat=len(variables)):
        env = dict(zip(variables, values))
        row = dict(env)
        for title, f in formulas.items():
            row[title] = bool(f(**env))
        rows.append(row)
    table = pd.DataFrame(rows)
    if letters:
        table = table.replace({True: "T", False: "F"})
    return table


# ── Sets ────────────────────────────────────────────────────────────────────
def jaccard(a, b) -> float:
    """Jaccard index |A ∩ B| / |A ∪ B| of two collections (1.0 for two empty sets)."""
    a, b = set(a), set(b)
    union = a | b
    return len(a & b) / len(union) if union else 1.0


def _venn_order(x):
    """Sort key for Venn-diagram labels: numbers in numeric order first, then everything else as text."""
    if isinstance(x, (int, float, np.integer, np.floating)) and not isinstance(x, bool):
        return (0, float(x), "")
    return (1, 0.0, str(x))


def draw_venn(sets: dict, universe=None, ax=None, show_elements: bool = True, max_items: int = 6,
              title: str | None = None, highlight=None):
    """Draw a Venn diagram of two or three sets with matplotlib only.

    ``sets`` maps a label to a Python set, e.g. ``{"S": {1, 2, 3}, "T": {3, 4}}``.  Each region
    shows its elements (or ``n = …`` if it has more than ``max_items``).  If ``universe`` is given,
    a rectangle is drawn and the elements outside every set are listed in a corner.
    ``highlight`` is a function of the membership tuple, e.g. ``lambda s, t: s and not t`` for
    S \\ T; the regions where it is true are shaded.  Returns the Axes.
    """
    labels = list(sets)
    if len(labels) not in (2, 3):
        raise ValueError("draw_venn draws two or three sets")
    if ax is None:
        _, ax = plt.subplots(figsize=(4.6, 3.8))
    if len(labels) == 2:
        centres = [(-0.55, 0.0), (0.55, 0.0)]
    else:
        centres = [(-0.55, 0.32), (0.55, 0.32), (0.0, -0.6)]
    radius = 1.0
    colours = ["tab:blue", "tab:orange", "tab:green"]
    # classify a fine grid of points to find each region (used for shading and label positions)
    gx, gy = np.meshgrid(np.linspace(-2.2, 2.2, 441), np.linspace(-2.0, 1.9, 391))
    inside = [((gx - cx) ** 2 + (gy - cy) ** 2) <= radius ** 2 for cx, cy in centres]
    if highlight is not None:
        mask = np.zeros_like(gx, dtype=bool)
        for member in itertools.product([True, False], repeat=len(labels)):
            if any(member) and highlight(*member):
                region = np.ones_like(gx, dtype=bool)
                for k, m in enumerate(member):
                    region &= inside[k] if m else ~inside[k]
                mask |= region
        ax.contourf(gx, gy, mask.astype(float), levels=[0.5, 1.5], colors=["#ffd54f"], alpha=0.8)
    for (cx, cy), lab, col in zip(centres, labels, colours):
        ax.add_patch(plt.Circle((cx, cy), radius, fill=False, lw=2, color=col))
        lx = cx + (-1.0 if cx < 0 else 1.0 if cx > 0 else 0.0) * 0.95
        ly = cy + (0.95 if cy >= 0 else -1.15)
        ax.text(lx, ly, lab, ha="center", va="center", fontsize=11, fontweight="bold", color=col)
    elements = set().union(*sets.values())
    for member in itertools.product([True, False], repeat=len(labels)):
        if not any(member):
            continue
        region_items = [x for x in elements if all((x in sets[l]) == m for l, m in zip(labels, member))]
        region = np.ones_like(gx, dtype=bool)
        for k, m in enumerate(member):
            region &= inside[k] if m else ~inside[k]
        if not region.any():
            continue
        px, py = gx[region].mean(), gy[region].mean()
        listing = ", ".join(str(x) for x in sorted(region_items, key=_venn_order))
        if show_elements and len(region_items) <= max_items and len(listing) <= 16:
            text = listing if region_items else "∅"
        else:
            text = f"n = {len(region_items)}"
        ax.text(px, py, text, ha="center", va="center", fontsize=8, wrap=True)
    if universe is not None:
        ax.add_patch(plt.Rectangle((-2.1, -1.9), 4.2, 3.7, fill=False, lw=1, color="0.4"))
        outside = sorted(set(universe) - elements, key=_venn_order)
        text = ", ".join(map(str, outside)) if len(outside) <= max_items else f"n = {len(outside)}"
        ax.text(-2.0, -1.8, "U: " + (text if outside else "∅"), fontsize=8, va="bottom", color="0.3")
    ax.set_xlim(-2.2, 2.2)
    ax.set_ylim(-2.0, 1.9)
    ax.set_aspect("equal")
    ax.axis("off")
    if title:
        ax.set_title(title)
    return ax


# ── Graphs ──────────────────────────────────────────────────────────────────
def circle_layout(nodes: list) -> dict:
    """Place nodes evenly on a circle (first node at the top, clockwise)."""
    n = len(nodes)
    angles = np.pi / 2 - 2 * np.pi * np.arange(n) / max(n, 1)
    return {v: (float(np.cos(a)), float(np.sin(a))) for v, a in zip(nodes, angles)}


def tree_layout(edges: list, root) -> dict:
    """Positions for drawing a rooted tree top-down: root at the top, leaves evenly spaced.

    ``edges`` are (parent, child) pairs or undirected pairs; the tree is explored from ``root``.
    """
    nbrs = {}
    for u, v in edges:
        nbrs.setdefault(u, []).append(v)
        nbrs.setdefault(v, []).append(u)
    children, order, seen, stack = {}, [], {root}, [root]
    while stack:
        u = stack.pop()
        order.append(u)
        children[u] = [w for w in nbrs.get(u, []) if w not in seen]
        seen.update(children[u])
        stack.extend(reversed(children[u]))
    depth = {root: 0}
    for u in order:
        for w in children[u]:
            depth[w] = depth[u] + 1
    x_pos, next_leaf = {}, [0]

    def place(u):
        if not children[u]:
            x_pos[u] = float(next_leaf[0])
            next_leaf[0] += 1
        else:
            for w in children[u]:
                place(w)
            x_pos[u] = float(np.mean([x_pos[w] for w in children[u]]))

    place(root)
    return {u: (x_pos[u], -float(depth[u])) for u in order}


def adjacency_matrix(nodes: list, edges: list, directed: bool = False) -> np.ndarray:
    """Adjacency matrix A with A[i, j] = number of edges from nodes[i] to nodes[j].

    For an undirected graph every edge is counted in both directions (A is symmetric);
    a self-loop {v, v} adds 1 to the diagonal entry A[v, v].  List each undirected edge once:
    giving both (u, v) and (v, u) with ``directed=False`` counts that edge twice (a multigraph).
    """
    index = {v: i for i, v in enumerate(nodes)}
    A = np.zeros((len(nodes), len(nodes)), dtype=int)
    for u, v in edges:
        A[index[u], index[v]] += 1
        if not directed and u != v:
            A[index[v], index[u]] += 1
    return A


def draw_graph(edges: list, nodes=None, directed: bool = False, pos=None, ax=None, node_colors=None,
               edge_labels=None, title: str | None = None, font_size: int = 9):
    """Draw a small graph with matplotlib only (no extra packages needed).

    ``edges`` is a list of (u, v) pairs; ``nodes`` (optional) adds isolated nodes and fixes the
    order; ``pos`` maps node → (x, y) (default: ``circle_layout``).  Directed edges get arrows,
    self-loops are drawn as small rings above the node, ``edge_labels`` maps (u, v) → text (e.g. a
    weight) and ``node_colors`` maps node → colour.  Node circles grow with the length of their
    label.  Returns the Axes.
    """
    from matplotlib.transforms import offset_copy

    if nodes is None:
        nodes = []
        for u, v in edges:
            for w in (u, v):
                if w not in nodes:
                    nodes.append(w)
    pos = circle_layout(list(nodes)) if pos is None else pos
    if ax is None:
        _, ax = plt.subplots(figsize=(4.2, 3.6))
    radius = {v: max(0.62 * font_size * len(str(v)) / 2 + 4, 0.9 * font_size) for v in nodes}  # points
    for u, v in edges:
        if u == v:
            ring = offset_copy(ax.transData, fig=ax.figure, x=0, y=1.25 * radius[u], units="points")
            ax.scatter([pos[u][0]], [pos[u][1]], s=(1.3 * radius[u]) ** 2, facecolors="none",
                       edgecolors="0.35", linewidths=1.3, transform=ring, zorder=1)
            continue
        style = "-|>" if directed else "-"
        ax.annotate("", xy=pos[v], xytext=pos[u],
                    arrowprops=dict(arrowstyle=style, color="0.35", lw=1.3, mutation_scale=12,
                                    shrinkA=radius[u], shrinkB=radius[v],
                                    connectionstyle="arc3,rad=0.08" if directed else "arc3,rad=0"))
        if edge_labels and (u, v) in edge_labels:
            (x1, y1), (x2, y2) = pos[u], pos[v]
            ax.text((x1 + x2) / 2, (y1 + y2) / 2, str(edge_labels[(u, v)]), fontsize=font_size - 1,
                    ha="center", va="center", color="darkred", zorder=4,
                    bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.85))
    xs = [pos[v][0] for v in nodes]
    ys = [pos[v][1] for v in nodes]
    colours = [(node_colors or {}).get(v, "#cfe2f3") for v in nodes]
    ax.scatter(xs, ys, s=[(2 * radius[v]) ** 2 for v in nodes], c=colours, edgecolors="0.2",
               linewidths=1.2, zorder=2, clip_on=False)
    for v in nodes:
        ax.text(pos[v][0], pos[v][1], str(v), ha="center", va="center", fontsize=font_size, zorder=3,
                clip_on=False)
    ax.margins(0.22)
    ax.set_aspect("equal", adjustable="datalim")
    ax.axis("off")
    if title:
        ax.set_title(title)
    return ax


# ── Linear algebra ──────────────────────────────────────────────────────────
def plot_vectors(vectors: list, labels=None, colors=None, ax=None, lim=None, title: str | None = None,
                 origin=(0.0, 0.0)):
    """Draw 2-D vectors as arrows starting at ``origin`` (default: the origin of the plane)."""
    if ax is None:
        _, ax = plt.subplots(figsize=(4.0, 4.0))
    default = ["tab:blue", "tab:orange", "tab:green", "tab:red", "tab:purple", "tab:brown"]
    colors = colors or [default[i % len(default)] for i in range(len(vectors))]
    ox, oy = origin
    for i, v in enumerate(vectors):
        ax.quiver(ox, oy, v[0], v[1], angles="xy", scale_units="xy", scale=1, color=colors[i], width=0.012)
        if labels:
            ax.text(ox + v[0] * 1.07, oy + v[1] * 1.07, labels[i], color=colors[i], fontsize=10,
                    ha="center", va="center")
    if lim is None:
        m = max([abs(c) for v in vectors for c in (ox + v[0], oy + v[1])] + [1.0]) * 1.25
        lim = (-m, m)
    ax.set_xlim(*lim)
    ax.set_ylim(*lim)
    ax.axhline(0, color="0.6", lw=0.8)
    ax.axvline(0, color="0.6", lw=0.8)
    ax.set_aspect("equal")
    ax.grid(alpha=0.3)
    if title:
        ax.set_title(title)
    return ax


def format_matrix(M, n_coef=None, width: int = 7) -> str:
    """Pretty-print a matrix of numbers, Fractions or SymPy rationals (complex entries with a zero
    imaginary part print as reals); a bar ``|`` is drawn after ``n_coef`` columns."""
    M = np.asarray(M, dtype=object)

    def fmt(x):
        if getattr(x, "is_Rational", False):            # a SymPy Rational/Integer → exact fraction
            x = Fraction(int(x.p), int(x.q))
        if isinstance(x, Fraction):
            return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"
        if isinstance(x, (int, np.integer)):
            return str(int(x))
        if isinstance(x, (complex, np.complexfloating)):
            if abs(x.imag) > 1e-12:
                return f"{x.real:.3g}{x.imag:+.3g}i"
            x = x.real
        x = float(x)
        return "0" if abs(x) < 1e-12 else f"{x:.4g}"

    lines = []
    for row in M:
        cells = [fmt(x).rjust(width) for x in row]
        if n_coef is not None and n_coef < len(cells):
            cells = cells[:n_coef] + ["  |"] + cells[n_coef:]
        lines.append("[" + "".join(cells) + " ]")
    return "\n".join(lines)


def gauss_jordan(M, n_coef=None, verbose: bool = False, tol: float = 1e-12):
    """Reduce a matrix to row-reduced echelon form (RREF) with the three elementary row operations.

    Integer or Fraction input is reduced *exactly* with fractions (as on paper); float input with
    floating-point arithmetic.  For an augmented matrix [A | b] pass ``n_coef`` = number of columns
    of A, so that pivots are only chosen among the coefficient columns.  With ``verbose=True`` every
    operation (Type I swap, Type II scale, Type III add a multiple of a row) is printed together
    with the matrix after it.  Returns ``(R, pivot_columns)``.
    """
    A = np.asarray(M, dtype=object)
    exact = all(isinstance(x, (int, np.integer, Fraction)) for x in A.flat)
    if exact:
        R = np.array([[Fraction(int(x)) if not isinstance(x, Fraction) else x for x in row] for row in A],
                     dtype=object)
    else:
        R = np.asarray(A, dtype=float).copy()
    n_rows, n_cols = R.shape
    n_coef = n_cols if n_coef is None else n_coef
    is_zero = (lambda x: x == 0) if exact else (lambda x: abs(x) < tol)
    pivots, r = [], 0
    for c in range(n_coef):
        if r == n_rows:
            break
        candidates = [i for i in range(r, n_rows) if not is_zero(R[i, c])]
        if not candidates:
            continue
        p = candidates[0] if exact else max(candidates, key=lambda i: abs(R[i, c]))
        if p != r:
            R[[r, p]] = R[[p, r]]
            if verbose:
                print(f"Type I:   swap R{r + 1} ↔ R{p + 1}")
                print(format_matrix(R, n_coef if n_coef < n_cols else None))
        if R[r, c] != 1:
            factor = (1 / R[r, c]) if not exact else Fraction(1) / R[r, c]
            R[r] = R[r] * factor
            if verbose:
                print(f"Type II:  R{r + 1} ← ({format_matrix([[factor]]).strip('[] ')}) · R{r + 1}")
                print(format_matrix(R, n_coef if n_coef < n_cols else None))
        for i in range(n_rows):
            if i != r and not is_zero(R[i, c]):
                beta = -R[i, c]
                R[i] = R[i] + beta * R[r]
                if verbose:
                    print(f"Type III: R{i + 1} ← R{i + 1} + ({format_matrix([[beta]]).strip('[] ')}) · R{r + 1}")
                    print(format_matrix(R, n_coef if n_coef < n_cols else None))
        if not exact:
            R[np.abs(R) < tol] = 0.0
        pivots.append(c)
        r += 1
    return R, pivots


# ── DNA sequences and Markov chains ─────────────────────────────────────────
NUCLEOTIDES = ("A", "C", "G", "T")
COMPLEMENT = {"A": "T", "C": "G", "G": "C", "T": "A"}

# First-order Markov-chain transition probabilities P(next | current) for DNA, rows = current base,
# columns = next base, both in the order A, C, G, T.  Rounded to two decimals from the classic
# CpG-island ("+") and background ("−") models of Durbin et al. (1998), Table 3.1, which were
# estimated from human sequence.  In CpG islands a C is often followed by a G; elsewhere CG is rare
# because methylated C in CpG mutates to T.
CPG_ISLAND_TRANSITIONS = np.array([
    [0.18, 0.27, 0.43, 0.12],
    [0.17, 0.37, 0.27, 0.19],
    [0.16, 0.34, 0.37, 0.13],
    [0.08, 0.36, 0.38, 0.18],
])
BACKGROUND_TRANSITIONS = np.array([
    [0.30, 0.20, 0.29, 0.21],
    [0.32, 0.30, 0.08, 0.30],
    [0.25, 0.25, 0.29, 0.21],
    [0.18, 0.24, 0.29, 0.29],
])


def reverse_complement(seq: str) -> str:
    """Reverse complement of a DNA string (A↔T, C↔G, read backwards)."""
    return "".join(COMPLEMENT[b] for b in reversed(seq))


def simulate_dna(length: int, transitions=None, initial=None, seed: int = 0) -> str:
    """Random DNA string.  Without ``transitions`` the bases are i.i.d. uniform; otherwise they
    follow a first-order Markov chain with the given 4 × 4 transition matrix (order A, C, G, T)
    and initial distribution ``initial`` (default uniform)."""
    rng = np.random.default_rng(seed)
    initial = np.full(4, 0.25) if initial is None else np.asarray(initial, dtype=float)
    if transitions is None:
        return "".join(rng.choice(list(NUCLEOTIDES), size=length, p=initial))
    P = np.asarray(transitions, dtype=float)
    states = [rng.choice(4, p=initial)]
    for _ in range(length - 1):
        states.append(rng.choice(4, p=P[states[-1]]))
    return "".join(NUCLEOTIDES[s] for s in states)


def kmer_counts(seq: str, k: int) -> dict:
    """Counts of every overlapping k-mer (substring of length k) of ``seq``, sorted alphabetically."""
    counts = Counter(seq[i:i + k] for i in range(len(seq) - k + 1))
    return dict(sorted(counts.items()))


def markov_log_probability(seq: str, transitions, initial=None) -> float:
    """Natural-log probability of a DNA string under a first-order Markov chain:
    log P(x1) + Σ log P(x_t | x_{t-1})."""
    idx = {b: i for i, b in enumerate(NUCLEOTIDES)}
    initial = np.full(4, 0.25) if initial is None else np.asarray(initial, dtype=float)
    P = np.asarray(transitions, dtype=float)
    logp = np.log(initial[idx[seq[0]]])
    for a, b in zip(seq[:-1], seq[1:]):
        logp += np.log(P[idx[a], idx[b]])
    return float(logp)


# ── Gene expression ─────────────────────────────────────────────────────────
# Named genes of the simulated infection experiment.  The infection-response genes are real genes
# known to be induced during infection (cytokines, interferon-stimulated genes, acute-phase
# proteins; lysozyme, LYZ, is an antimicrobial enzyme rather than a classic acute-phase protein and is
# grouped with them only for simplicity); the reference genes are classic "housekeeping" genes used
# to normalise qPCR.
INFECTION_PATHWAYS = {
    "cytokine signalling": ["IL1B", "TNF", "IL6", "CXCL8"],
    "interferon response": ["IRF1", "STAT1", "MX1", "ISG15"],
    "acute phase": ["SAA1", "HAMP", "C3", "LYZ"],
}
HOUSEKEEPING_GENES = ["ACTB", "GAPDH", "EEF1A1", "RPL13A", "TBP", "HPRT1",
                      "PPIA", "UBC", "YWHAZ", "SDHA", "TUBA1A", "B2M"]

# A simplified, illustrative cartoon of innate-immune signalling among the named genes
# (regulator → target).  NF-κB (NFKB1) induces cytokines; TNF and IL-1β activate NF-κB (a feedback
# loop); IL-6 acts through STAT3 to induce acute-phase genes; STAT1 induces interferon-stimulated genes.
INFLAMMATION_NETWORK_EDGES = [
    ("NFKB1", "IL1B"), ("NFKB1", "TNF"), ("NFKB1", "IL6"), ("NFKB1", "CXCL8"),
    ("TNF", "NFKB1"), ("IL1B", "NFKB1"), ("IL6", "STAT3"), ("STAT3", "SAA1"),
    ("STAT3", "HAMP"), ("STAT3", "C3"), ("STAT1", "IRF1"), ("STAT1", "MX1"),
    ("STAT1", "ISG15"), ("IRF1", "ISG15"), ("NFKB1", "LYZ"),
]


def simulate_tissue_expression(n_genes: int = 400, tissues=("spleen", "kidney", "liver"), n_reps: int = 4,
                               seed: int = 2680) -> dict:
    """SIMULATED log2 gene expression from an infection experiment in several tissues.

    Every tissue has ``n_reps`` control and ``n_reps`` infected samples.  The 12 genes of
    ``INFECTION_PATHWAYS`` respond to infection in every tissue (up by 1.5–3 log2 units); further
    "g…" genes respond in one tissue only or in two tissues, so the sets of truly changed genes
    overlap like the differentially-expressed-gene sets of a real multi-tissue study.  The 12
    ``HOUSEKEEPING_GENES`` are stable (tiny noise, no response).  About a third of all genes differ in
    baseline level between tissues.

    Returns a dict with ``X`` (samples × genes, log2 expression), ``samples`` (DataFrame with
    columns sample, tissue, condition), ``genes`` (list), ``true_lfc`` (DataFrame tissues × genes,
    true infected − control difference), ``true_de`` (dict tissue → set of truly changed genes),
    ``pathways`` (dict pathway → genes) and ``source``.
    """
    rng = np.random.default_rng(seed)
    named = [g for genes in INFECTION_PATHWAYS.values() for g in genes]
    n_other = n_genes - len(named) - len(HOUSEKEEPING_GENES)
    if n_other < 60:
        raise ValueError("n_genes must be at least 84")
    genes = named + HOUSEKEEPING_GENES + [f"g{i:03d}" for i in range(1, n_other + 1)]
    J, T = len(genes), len(tissues)
    base = rng.normal(7.0, 1.8, J)
    base[len(named):len(named) + len(HOUSEKEEPING_GENES)] = rng.uniform(9.0, 12.0, len(HOUSEKEEPING_GENES))
    tissue_shift = rng.normal(0.0, 1.0, (T, J)) * (rng.random(J) < 0.35)
    tissue_shift[:, len(named):len(named) + len(HOUSEKEEPING_GENES)] = 0.0
    lfc = np.zeros((T, J))
    lfc[:, :len(named)] = rng.uniform(1.5, 3.0, (T, len(named)))
    other = list(range(len(named) + len(HOUSEKEEPING_GENES), J))
    rng.shuffle(other)
    sizes_single = [24, 18, 14, 12, 10][:T]
    pairs = list(itertools.combinations(range(T), 2))
    sizes_pair = [10, 5, 4, 3, 3, 2, 2, 2, 2, 2][:len(pairs)]
    k = 0

    def effect(m):
        return rng.uniform(1.0, 2.5, m) * np.where(rng.random(m) < 0.7, 1.0, -1.0)

    for t, m in enumerate(sizes_single):
        idx = other[k:k + m]
        lfc[t, idx] = effect(m)
        k += m
    for (t1, t2), m in zip(pairs, sizes_pair):
        idx = other[k:k + m]
        e = effect(m)
        lfc[t1, idx] = e
        lfc[t2, idx] = e * rng.uniform(0.8, 1.2, m)
        k += m
    noise_sd = rng.uniform(0.25, 0.55, J)
    noise_sd[len(named):len(named) + len(HOUSEKEEPING_GENES)] = 0.08
    rows, X = [], []
    for t, tissue in enumerate(tissues):
        for condition in ("control", "infected"):
            for r in range(1, n_reps + 1):
                mean = base + tissue_shift[t] + (lfc[t] if condition == "infected" else 0.0)
                X.append(mean + rng.normal(0.0, noise_sd))
                rows.append((f"{tissue}_{condition[:3]}{r}", tissue, condition))
    samples = pd.DataFrame(rows, columns=["sample", "tissue", "condition"])
    true_lfc = pd.DataFrame(lfc, index=list(tissues), columns=genes)
    true_de = {tissue: {g for g, v in zip(genes, lfc[t]) if v != 0} for t, tissue in enumerate(tissues)}
    return {"X": np.array(X), "samples": samples, "genes": genes, "true_lfc": true_lfc,
            "true_de": true_de, "pathways": {k_: list(v) for k_, v in INFECTION_PATHWAYS.items()},
            "source": "SIMULATED log2 expression (BiologyToMath simulate_tissue_expression)"}


CELL_TYPE_MARKERS = {
    "T cell": ["CD3E", "CD3D", "IL7R"],
    "B cell": ["CD79A", "MS4A1", "CD19"],
    "macrophage": ["CD68", "LYZ", "CSF1R"],
    "fibroblast": ["COL1A1", "COL1A2", "DCN"],
}


def simulate_cell_counts(n_cells=(160, 120, 90, 70), cell_types=("T cell", "B cell", "macrophage", "fibroblast"),
                         n_background: int = 28, overdispersion: float = 0.0, seed: int = 680) -> dict:
    """SIMULATED single-cell RNA counts (molecules of each gene detected in each cell).

    Each cell type has a true mean count λ for every gene: its three ``CELL_TYPE_MARKERS`` genes are
    high (λ ≈ 6–15) in that type and low (≈ 0.1–0.5) elsewhere; ``n_background`` other genes share
    similar λ (≈ 0.2–4) in all types.  Counts are Poisson(λ); with ``overdispersion`` φ > 0 each
    cell's λ is first multiplied by a Gamma(1/φ, φ) factor (mean 1), which makes counts negative-
    binomial with variance λ + φλ² — closer to real data.

    Returns a dict with ``counts`` (cells × genes, int), ``labels`` (cell type of each cell),
    ``genes``, ``rates`` (DataFrame cell types × genes of true λ) and ``source``.
    """
    rng = np.random.default_rng(seed)
    markers = [g for t in cell_types for g in CELL_TYPE_MARKERS[t]]
    genes = markers + [f"bg{i:02d}" for i in range(1, n_background + 1)]
    rates = np.zeros((len(cell_types), len(genes)))
    bg = rng.uniform(0.2, 4.0, n_background)
    for t, ctype in enumerate(cell_types):
        for j, g in enumerate(markers):
            rates[t, j] = rng.uniform(6.0, 15.0) if g in CELL_TYPE_MARKERS[ctype] else rng.uniform(0.1, 0.5)
        rates[t, len(markers):] = bg * rng.uniform(0.8, 1.25, n_background)
    labels, counts = [], []
    for t, (ctype, n) in enumerate(zip(cell_types, n_cells)):
        lam = np.tile(rates[t], (n, 1))
        if overdispersion > 0:
            lam = lam * rng.gamma(1.0 / overdispersion, overdispersion, size=lam.shape)
        counts.append(rng.poisson(lam))
        labels += [ctype] * n
    return {"counts": np.vstack(counts), "labels": np.array(labels), "genes": genes,
            "rates": pd.DataFrame(rates, index=list(cell_types), columns=genes),
            "source": "SIMULATED single-cell counts (BiologyToMath simulate_cell_counts)"}


# ── Genetics ────────────────────────────────────────────────────────────────
def simulate_genotypes(n: int, p: float, inbreeding: float = 0.0, seed: int = 1866) -> np.ndarray:
    """SIMULATED genotypes of ``n`` diploid individuals at one SNP, coded 0/1/2 = number of copies of
    the allele with frequency ``p``.  With ``inbreeding`` F = 0 the genotype frequencies follow
    Hardy–Weinberg proportions ((1−p)², 2p(1−p), p²); F > 0 moves individuals from heterozygotes to
    homozygotes: P(1) = 2p(1−p)(1−F)."""
    rng = np.random.default_rng(seed)
    q = 1.0 - p
    probs = np.array([q * q + inbreeding * p * q, 2 * p * q * (1 - inbreeding), p * p + inbreeding * p * q])
    return rng.choice(3, size=n, p=probs / probs.sum())


# ── Clinical studies ────────────────────────────────────────────────────────
def simulate_cholesterol_trial(n: int = 12, effect: float = -18.0, seed: int = 2026) -> pd.DataFrame:
    """SIMULATED paired drug trial: LDL cholesterol (mg/dL) of ``n`` patients before and after
    treatment.  Patients differ a lot from each other (between-patient SD 30 mg/dL around 160), the
    measurement/day-to-day noise is smaller (SD 10), and the drug changes LDL by ``effect`` on
    average (the hidden truth).  Columns: patient, before, after."""
    rng = np.random.default_rng(seed)
    level = rng.normal(160.0, 30.0, n)
    before = level + rng.normal(0.0, 10.0, n)
    after = level + effect + rng.normal(0.0, 10.0, n)
    return pd.DataFrame({"patient": [f"P{i + 1:02d}" for i in range(n)],
                         "before": before.round(1), "after": after.round(1)})


INSULIN_TRUE_COEFFICIENTS = {"intercept": -4.0, "bmi": 0.55, "age": 0.04, "glucose": 0.06}
INSULIN_TRUE_SIGMA = 2.5


def simulate_insulin_study(n: int = 120, seed: int = 1921) -> pd.DataFrame:
    """SIMULATED clinical study: fasting insulin (µU/mL) of ``n`` adults as a linear function of
    BMI (kg/m²), age (years) and fasting glucose (mg/dL) plus Gaussian noise.  The true coefficients
    are ``INSULIN_TRUE_COEFFICIENTS`` and the noise SD is ``INSULIN_TRUE_SIGMA``.  Columns: bmi, age,
    glucose, insulin."""
    rng = np.random.default_rng(seed)
    bmi = rng.normal(27.0, 4.5, n).clip(17, 45)
    age = rng.uniform(20, 75, n)
    glucose = (88 + 1.1 * (bmi - 27) + 0.15 * (age - 45) + rng.normal(0, 9, n)).clip(65, 160)
    c = INSULIN_TRUE_COEFFICIENTS
    insulin = c["intercept"] + c["bmi"] * bmi + c["age"] * age + c["glucose"] * glucose \
        + rng.normal(0.0, INSULIN_TRUE_SIGMA, n)
    return pd.DataFrame({"bmi": bmi.round(1), "age": age.round(0), "glucose": glucose.round(0),
                         "insulin": insulin.round(2)})
